def test_fallback_report_lists_missing_details_and_disclaims_ai():
    report = build_fallback_report(
        {
            "title": "App crashes",
            "body": "It stopped working.",
            "url": "https://github.com/acme/app/issues/1",
        }
    )
    assert "reproduction steps" in report
    assert "error details" in report
    assert "Priority suggestion" in report
    assert "not generated by an AI model" in report
    assert "Deterministic, keyword-based checklist" in report


def test_fallback_report_detects_diagnostic_evidence_with_word_boundaries():
    report = build_fallback_report(
        {
            "title": "Crash report",
            "body": (
                "Steps to reproduce: open the app. Traceback is attached. "
                "Version 2.4 on Linux. Expected behavior differs from actual behavior."
            ),
        }
    )
    detected = (
        "reproduction steps, error details, environment and version, "
        "expected versus actual behaviour"
    )
    assert detected in report
    assert "No omissions detected" in report


def test_fallback_report_does_not_treat_substrings_as_evidence():
    issue_body = "The dialog opens slowly in the catalogue. Expected behavior is to open faster."
    report = build_fallback_report({"title": "Dialog catalogue issue", "body": issue_body})
    assert "error details" in report
    assert "environment and version" in report
    assert "Diagnostic signals detected: None detected" in report


def test_fallback_report_flags_potential_impact_without_claiming_severity():
    report = build_fallback_report(
        {"title": "Production data loss", "body": "Users report data corruption."}
    )
    assert "Potentially high impact" in report
    assert "not a severity determination" in report


